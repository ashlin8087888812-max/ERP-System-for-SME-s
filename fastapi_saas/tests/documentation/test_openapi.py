class TestOpenAPISchema:
    """Test OpenAPI schema validity"""
    
    def test_openapi_schema_exists(self, client):
        """Test OpenAPI schema is accessible"""
        response = client.get("/api/v1/openapi.json")
        assert response.status_code == 200
        
        schema = response.json()
        assert "openapi" in schema
        assert "info" in schema
        assert "paths" in schema
    
    def test_all_endpoints_documented(self, client):
        """Test all endpoints are in OpenAPI schema"""
        response = client.get("/api/v1/openapi.json")
        schema = response.json()
        
        paths = schema["paths"]
        
        # Critical endpoints should be documented
        assert "/api/v1/auth/login" in paths
        assert "/api/v1/scm/purchase-orders" in paths
        assert "/health" in paths
    
    def test_request_examples_valid(self, client):
        """Test request body examples are valid"""
        response = client.get("/api/v1/openapi.json")
        schema = response.json()
        
        # Get PO create endpoint
        po_endpoint = schema["paths"]["/api/v1/scm/purchase-orders"]["post"]
        
        # Should have request body
        assert "requestBody" in po_endpoint
        
        # Should have example
        request_body = po_endpoint["requestBody"]
        assert "content" in request_body
        assert "application/json" in request_body["content"]
    
    def test_response_examples_valid(self, client):
        """Test response examples are valid"""
        response = client.get("/api/v1/openapi.json")
        schema = response.json()
        
        # Get health endpoint
        health_endpoint = schema["paths"]["/health"]["get"]
        
        # Should have responses
        assert "responses" in health_endpoint
        assert "200" in health_endpoint["responses"]
    
    def test_authentication_documented(self, client):
        """Test authentication is documented"""
        response = client.get("/api/v1/openapi.json")
        schema = response.json()
        
        # Should have security schemes
        assert "components" in schema
        assert "securitySchemes" in schema["components"]
    
    def test_error_responses_documented(self, client):
        """Test error responses are documented"""
        response = client.get("/api/v1/openapi.json")
        schema = response.json()
        
        # Get PO endpoint
        po_endpoint = schema["paths"]["/api/v1/scm/purchase-orders"]["post"]
        
        # Should document error responses
        responses = po_endpoint["responses"]
        assert "422" in responses  # Validation error
        # assert "403" in responses or "401" in responses  # Auth error - not auto-generated by default


